'use client';
import { useState } from 'react';

/* Щит автоматизации в разрезе. «Каждая линия подписана и заложен резерв» —
   обещание, пока его не показали: на схеме видно и подписи, и пустые слоты.
   Это же и есть проверяемый признак работы, по которому щит оценивают —
   не марка автоматов, а порядок и запас.

   Названия групп — обобщённые, не с конкретного объекта: состав щита у
   каждого свой, и выдавать один за типовой было бы выдумкой. */
type Ряд = { id: string; имя: string; занято: number; текст: string; вид: 'сила' | 'слаботочка' | 'резерв' };

const РЯДЫ: Ряд[] = [
  { id: 'vvod', имя: 'Ввод и защита', занято: 4, вид: 'сила',
    текст: 'Вводной автомат, устройство защитного отключения, ограничитель перенапряжения. Отсюда считается вся селективность: при коротком замыкании в комнате не должен гаснуть дом.' },
  { id: 'svet', имя: 'Освещение по группам', занято: 10, вид: 'сила',
    текст: 'Каждая группа света — своя линия и свой модуль диммирования. Сцена меняет яркость групп, а не щёлкает одним выключателем: поэтому групп много и они разведены заранее.' },
  { id: 'rozetki', имя: 'Розеточные группы', занято: 8, вид: 'сила',
    текст: 'Управляемые розетки идут отдельной линией через модуль в щите. Переходник в розетке решает ту же задачу до первой перезагрузки роутера и не годится там, где нагрузка серьёзная.' },
  { id: 'klimat', имя: 'Климат и приводы', занято: 6, вид: 'сила',
    текст: 'Приводы клапанов отопления, вентиляция, увлажнение. Поконтурное управление начинается здесь: без отдельных линий тёплый пол в спальне живёт по расписанию всего этажа.' },
  { id: 'shina', имя: 'Шина и контроллер', занято: 5, вид: 'слаботочка',
    текст: 'Контроллер, блок питания шины, модули ввода. Логика живёт здесь, а не на сервере производителя — при пропаже интернета сцены и климат продолжают работать.' },
  { id: 'set', имя: 'Сеть и слаботочка', занято: 6, вид: 'слаботочка',
    текст: 'Коммутатор, патч-панель, домофон, датчики. Отделено от силовой части внутри щита: наводки портят сигнал шины и звук мультирума.' },
  { id: 'rezerv', имя: 'Резерв под расширение', занято: 0, вид: 'резерв',
    текст: 'Пустые слоты оставляются намеренно. Пристроить комнату, добавить контур тёплого пола или зону света через три года — это установка модуля в готовый щит, а не его замена.' },
];

const ВСЕГО = 12;

export default function PanelBoard() {
  const [активен, setАктивен] = useState<string>('rezerv');
  const ряд = РЯДЫ.find((р) => р.id === активен) || РЯДЫ[0];

  return (
    <div className="board">
      <div className="board-fig" role="group" aria-label="Щит автоматизации по рядам">
        {РЯДЫ.map((р) => (
          <button key={р.id} type="button"
            className={`board-row${активен === р.id ? ' on' : ''} v-${р.вид}`}
            aria-pressed={активен === р.id}
            onClick={() => setАктивен(р.id)}>
            <span className="board-name">{р.имя}</span>
            <span className="board-slots" aria-hidden="true">
              {Array.from({ length: ВСЕГО }, (_, i) => (
                <i key={i} className={i < р.занято ? 'busy' : 'free'} />
              ))}
            </span>
            <span className="board-count">
              {р.занято ? `${р.занято} из ${ВСЕГО}` : `${ВСЕГО} свободно`}
            </span>
          </button>
        ))}
      </div>
      {/* Все семь пояснений в разметке: скрыт только показ. */}
      <div className="board-body">
        {РЯДЫ.map((р) => (
          <p key={р.id} className="board-text" hidden={активен !== р.id}>
            <b>{р.имя}.</b> {р.текст}
          </p>
        ))}
      </div>
    </div>
  );
}
