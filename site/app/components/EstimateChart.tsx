'use client';
import { useState } from 'react';

/* Смета как диаграмма, а не как шесть абзацев подряд. Долю нажимают — она
   раскрывается; текст при этом остаётся в разметке целиком, потому что его
   читает машина, а не только человек: на этом держится весь ИИ-поиск.

   Ширины долей заданы не по нашим числам — их у нас нет, они помечены как
   ожидающие подтверждения. Здесь это порядок этапов и их вес по смыслу:
   оборудование и монтаж — основные, сдача и сервис — короткие. Как только
   придут настоящие доли, они встанут сюда одним числом на этап. */
type Этап = { n: string; имя: string; текст: string; доля: number; цвет: string };

const ЭТАПЫ: Этап[] = [
  { n: '01', имя: 'Инженерный проект', доля: 12, цвет: 'var(--st1)',
    текст: 'Расчёт нагрузок, схема трасс от щита до каждого устройства, спецификация под сценарии. Документ, по которому работают монтажники.' },
  { n: '02', имя: 'Оборудование', доля: 34, цвет: 'var(--st2)',
    текст: 'Контроллеры, датчики, исполнительные устройства — приводы штор, клапаны климата, диммеры. Класс оборудования двигает смету сильнее всего.' },
  { n: '03', имя: 'Кабель и монтаж', доля: 28, цвет: 'var(--st3)',
    текст: 'Разводка трасс и щит автоматизации. На стадии черновой идёт параллельно общестроительным работам и почти не добавляет срока.' },
  { n: '04', имя: 'Пусконаладка', доля: 16, цвет: 'var(--st4)',
    текст: 'Программирование сценариев под то, как люди реально живут в доме, а не под шаблон. Отдельный этап после отделки.' },
  { n: '05', имя: 'Сдача и обучение', доля: 6, цвет: 'var(--st5)',
    текст: 'Прогон по объекту, передача жильцу, гарантия на систему в целом — отдельно на оборудование, отдельно на работы.' },
  { n: '06', имя: 'Сервис после сдачи', доля: 4, цвет: 'var(--st6)',
    текст: 'Заявка идёт в компанию, которая монтировала объект и знает его схему, а не в общий чат поддержки производителя устройства.' },
];

export default function EstimateChart() {
  const [открыт, setОткрыт] = useState<string | null>('02');

  return (
    <div className="est">
      <div className="est-bar" role="group" aria-label="Состав сметы по этапам">
        {ЭТАПЫ.map((э) => (
          <button
            key={э.n}
            type="button"
            className="est-seg"
            style={{ flexGrow: э.доля, background: э.цвет }}
            aria-expanded={открыт === э.n}
            aria-controls={`est-${э.n}`}
            onClick={() => setОткрыт(открыт === э.n ? null : э.n)}
            title={э.имя}
          >
            <span className="est-seg-n">{э.n}</span>
          </button>
        ))}
      </div>

      {/* Подписи под диаграммой: без них цветная полоса ничего не сообщает
          тому, кто не наводит и не нажимает. */}
      <ol className="est-legend">
        {ЭТАПЫ.map((э) => (
          <li key={э.n}>
            {/* Класс стоит всегда: раньше он подставлялся только выбранной
                доле, и остальные пять кнопок оставались без оформления —
                в тёмной теме это серая кнопка браузера по умолчанию. */}
            <button type="button" className={`est-leg${открыт === э.n ? ' on' : ''}`}
              onClick={() => setОткрыт(открыт === э.n ? null : э.n)}>
              <i style={{ background: э.цвет }} aria-hidden="true" />
              {э.имя}
            </button>
          </li>
        ))}
      </ol>

      {/* Все шесть текстов лежат в разметке всегда. Скрыт только показ:
          свернуть содержимое от машины значит потерять то, ради чего сайт
          и написан. */}
      <div className="est-body">
        {ЭТАПЫ.map((э) => (
          <div key={э.n} id={`est-${э.n}`} className="est-item" hidden={открыт !== э.n}>
            {/* Название доли — не заголовок раздела: пять из шести блоков
                скрыты, и обход страницы видел заголовок, за которым ничего
                нет. Текст тот же, роль другая. */}
            <p className="est-item-name">{э.n} · {э.имя}</p>
            <p>{э.текст}</p>
          </div>
        ))}
      </div>
    </div>
  );
}
