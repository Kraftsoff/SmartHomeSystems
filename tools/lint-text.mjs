/*
 * Проверка текста сайта на стандарт языка проекта (CLAUDE.md).
 *   node tools/lint-text.mjs [путь-к-html]
 *
 * Ловит то, что глазом на объёме не видно: канцелярит, филлеры, обороты
 * «не X, а Y» как приём, пассивный залог, абстракции вместо конкретики.
 * Выход: 0 — чисто, 1 — есть попадания.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const FILE = process.argv[2] || 'tz-site/prototype/mimismart-v5.html';
const src = readFileSync(resolve(FILE), 'utf8');

/* Файл — фрагмент без <body>, поэтому берём его целиком и снимаем скрипты,
   стили и разметку. Содержимое <template> входит: там лежит большая часть
   текста ответов. */
const text = src
  .replace(/<script[\s\S]*?<\/script>/g, ' ')
  .replace(/<style[\s\S]*?<\/style>/g, ' ')
  .replace(/<[^>]+>/g, ' ')
  .replace(/&[a-z]+;/g, ' ')
  .replace(/\s+/g, ' ');

/* В JS \b и \w работают только с латиницей, поэтому кириллические шаблоны с ними
   молчат. Границы слова задаём явно через (^|[^а-яё]) и класс [а-яё]. */
const RULES = [
  /* «является» ловим как канцелярит, но не как обычную связку. Исключения:
     цитаты норм («не является публичной офертой» — формула п. 1 ст. 437 ГК) и
     предикативное «ими и являются», где это живая русская конструкция. */
  { re: /(^|[^а-яё])явля[ею]тся([^а-яё]|$)/gi,
    skip: /ГК РФ|ст\.\s?\d|ФЗ-\d|публичной офертой|и явля[ею]тся/i,
    why: 'канцелярская связка «является» — заменить на глагол действия' },
  { re: /осуществля[ею]тся|производится монтаж|выполняется установка/gi, why: 'канцелярит «осуществляется» — сказать, кто и что делает' },
  { re: /(важно|следует|стоит|необходимо) (отметить|учитывать|учесть|помнить|понимать|обеспечить)/gi, why: 'филлер перед мыслью — начать сразу с мысли' },
  { re: /в современном мире|на сегодняшний день|в наше время|не секрет, что/gi, why: 'пустой зачин' },
  { re: /инновацион[а-яё]*|уникальн[а-яё]*|передов[а-яё]* технолог|современн[а-яё]* решени/gi, why: 'декларация вместо факта' },
  { re: /комплексный подход|широкий спектр|высокое качество|индивидуальный подход|гибкая система скидок/gi, why: 'штамп без содержания' },
  { re: /значимост[а-яё]*|эффективност[а-яё]* решени|оптимальн[а-яё]* решени/gi, why: 'абстракция — назвать конкретный эффект' },
  { re: /не просто [а-яё]+, а /gi, why: 'риторическая формула «не просто X, а Y»' },
  { re: /позволяет (значительно|существенно|максимально)/gi, why: 'усилитель без числа' },
  { re: /данн(ый|ая|ое|ые) (продукт|решени|систем|объект|подход)/gi, why: 'канцелярское «данный» вместо «этот»' },
  { re: /(^|[^а-яё])(гарантиру[ею]м|обеспечива[ею]м) (полн|абсолютн|максимальн)/gi, why: 'обещание без границ' },
];

/* Юридически значимое: сравнительное превосходство о СЕБЕ без опубликованного
   критерия — ст. 14.2 и 14.3 ФЗ-135, штраф от 100 000 ₽ (audit/06). Само слово
   «лучший» нарушением не является: оно встречается в цитате поискового запроса
   и в нейтральных описаниях («самый частый тупик»). Опасно только рядом с нами,
   поэтому смотрим окно вокруг совпадения. */
const SUPERLATIVE = /лучш(ий|ая|ее|ие|его|ую)|первы[йе] в росси|номер один|самы[йея] (покупаем|надёжн|дешёв|быстр|больш)[а-яё]*|единственн[а-яё]+ в росси/gi;
const ABOUT_US = /(^|[^а-яё])(мы|наш[а-яё]*|у нас|mimismart|мимисмарт)([^а-яё]|$)/i;
const superHits = [];
{
  let m;
  while ((m = SUPERLATIVE.exec(text)) !== null) {
    const win = text.slice(Math.max(0, m.index - 120), m.index + m[0].length + 90);
    /* Отрицание — не заявление. «Чего мы не утверждаем: что мы лучшие» это
       ровно та страница, которая от превосходства и отказывается. */
    const denies = /не утвержда[ею]м|не заявля[ею]м|не значит|не означает|чего мы не|не претенду/i.test(win);
    if (ABOUT_US.test(win) && !denies) superHits.push(win.trim());
  }
}

const hits = [];
for (const r of RULES) {
  let found = text.match(r.re);
  if (!found) continue;
  if (r.skip) {
    /* Проверяем окно вокруг каждого совпадения, а не весь текст. */
    found = found.filter((w) => {
      const i = text.indexOf(w);
      return !r.skip.test(text.slice(Math.max(0, i - 80), i + w.length + 80));
    });
    if (!found.length) continue;
  }
  const uniq = [...new Set(found.map((x) => x.toLowerCase()))];
  hits.push({ why: r.why, soft: !!r.soft, count: found.length, examples: uniq.slice(0, 4) });
}

/* Контекст вокруг каждого попадания — чтобы правку можно было сделать сразу. */
function context(word) {
  const i = text.toLowerCase().indexOf(word.toLowerCase());
  if (i < 0) return '';
  return '…' + text.slice(Math.max(0, i - 60), i + word.length + 60).trim() + '…';
}

let hard = superHits.length;
superHits.forEach((w) => {
  console.log('✗ превосходство о себе без критерия — ФЗ-135 ст. 14.2/14.3');
  console.log(`    …${w}…`);
});

for (const h of hits) {
  const mark = h.soft ? '·' : '✗';
  if (!h.soft) hard += h.count;
  console.log(`${mark} ${h.why} — ${h.count}`);
  h.examples.forEach((e) => console.log(`    ${context(e)}`));
}

console.log(`\nзнаков видимого текста: ${text.length}`);
if (!hits.length) console.log('✅ Попаданий нет.');
else console.log(hard ? `\n❌ Жёстких попаданий: ${hard}` : '\n✅ Только мягкие замечания.');
process.exit(hard ? 1 : 0);
